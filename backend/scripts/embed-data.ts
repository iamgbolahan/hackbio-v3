import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Writes src/serverless/embedded.ts so a serverless bundle can migrate and seed without reading files at run time.
const root = join(__dirname, "..");
const csv = (name: string) => readFileSync(join(root, "data/mock", name), "utf8");
const migrations = readdirSync(join(root, "prisma/migrations"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const out = `// Generated by scripts/embed-data.ts. Do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(
  migrations.map((name) => ({ name, sql: readFileSync(join(root, "prisma/migrations", name, "migration.sql"), "utf8") })),
)};
export const SEED_CSV = ${JSON.stringify({
  profiles: csv("mock_astronaut_profiles.csv"),
  baseline: csv("mock_baseline_sessions.csv"),
  ultrasound: csv("mock_ultrasound_measurements.csv"),
})} as const;
`;
writeFileSync(join(root, "src/serverless/embedded.ts"), out);
console.log("wrote src/serverless/embedded.ts", out.length, "bytes");
